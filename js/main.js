document.addEventListener('DOMContentLoaded', () => {
    // =========================
    // DOM ELEMENTS
    // =========================
    const nav = document.querySelector('.nav'); // Navigation bar
    const header = document.querySelector('header'); // Header element
    const html = document.documentElement; // <html> tag
    const langSwitcher = document.getElementById('lang-switcher'); // Language switcher button (desktop)
    const langSwitcherMobile = document.getElementById('lang-switcher-mobile'); // Language switcher button (mobile)
    const langText = langSwitcher.querySelector('.language-text'); // Language switcher text
    const langTextMobile = langSwitcherMobile ? langSwitcherMobile.querySelector('.language-text') : null; // Language switcher text (mobile)
    // Do not cache the NodeList at load time. Query inside updateContent to
    // ensure any dynamically added or modified elements with `data-key`
    // (like the contact cards) are included when switching languages.

    // =========================
    // LANGUAGE UTILITY FUNCTION
    // =========================
    // Returns current language from localStorage, defaults to Arabic
    const getStoredLanguage = () => {
        return localStorage.getItem('language') || 'ar';
    };

    // =========================
    // TRANSLATION FUNCTION
    // =========================
    // Updates all translatable content based on selected language
    const updateContent = (lang) => {
        // Update HTML lang and direction
        html.setAttribute('lang', lang);
        html.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

        // Update language switcher button text (both desktop and mobile)
        langText.textContent = lang === 'ar' ? 'English' : 'العربية';
        if (langTextMobile) {
            langTextMobile.textContent = lang === 'ar' ? 'English' : 'العربية';
        }

        // Query all translatable elements at the time of update so newly
        // injected or modified elements are picked up (fixes contact cards not updating).
        const elementsToTranslate = document.querySelectorAll('[data-key]');
        elementsToTranslate.forEach(element => {
            const key = element.getAttribute('data-key');
            if (translations[key] && translations[key][lang]) {
                // Special case: <title> tag
                if (element.tagName === 'TITLE') {
                    document.title = translations[key][lang];
                }
                // Special case: <a> tags (do not translate href)
                else if (element.tagName === 'A') {
                    element.textContent = translations[key][lang];
                }
                // Default: update text content
                else if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    element.placeholder = translations[key][lang];
                }
                // Default: update text content
                else {
                    element.textContent = translations[key][lang];
                }
            }
        });
    };

    // =========================
    // LANGUAGE TOGGLE HANDLER
    // =========================
    // Switches between Arabic and English
    const toggleLanguage = () => {
        const currentLang = getStoredLanguage();
        const newLang = currentLang === 'ar' ? 'en' : 'ar';
        localStorage.setItem('language', newLang);
        updateContent(newLang);
    };

    // =========================
    // INITIALIZATION
    // =========================
    // Set initial language on page load
    const initialLang = getStoredLanguage();
    updateContent(initialLang);

    // Attach click event to language switcher (both desktop and mobile)
    langSwitcher.addEventListener('click', toggleLanguage);
    if (langSwitcherMobile) {
        langSwitcherMobile.addEventListener('click', toggleLanguage);
    }

    // =========================
    // MOBILE NAV (HAMBURGER) TOGGLE
    // =========================
    const navToggle = document.getElementById('nav-toggle');
    // Ensure nav exists
    if (navToggle && nav) {
        // Sync aria-expanded with state
        const setAria = () => navToggle.setAttribute('aria-expanded', nav.classList.contains('mobile-open') ? 'true' : 'false');

        navToggle.addEventListener('click', (e) => {
            e.stopPropagation();
            nav.classList.toggle('mobile-open');
            setAria();
        });

        // Close mobile menu when clicking outside
        document.addEventListener('click', (e) => {
            if (!nav.classList.contains('mobile-open')) return;
            if (!nav.contains(e.target)) {
                nav.classList.remove('mobile-open');
                setAria();
            }
        });

        // Close when any nav link is clicked (good for single-page anchors)
        const navLinks = nav.querySelectorAll('.nav__menu a');
        navLinks.forEach(link => link.addEventListener('click', () => {
            if (nav.classList.contains('mobile-open')) {
                nav.classList.remove('mobile-open');
                setAria();
            }
        }));

        // Ensure menu closes when resizing up to desktop
        window.addEventListener('resize', () => {
            if (window.innerWidth > 980 && nav.classList.contains('mobile-open')) {
                nav.classList.remove('mobile-open');
                setAria();
            }
        });
    }

    // =========================
    // HEADER SCROLL EFFECT
    // =========================
    // Adds/removes 'scrolled' class to header/nav on scroll
    // Header stays visible at all times
    const scrollEffect = () => {
        const currentScrollY = window.scrollY;

        // Add scrolled class when scrolling down past 80px
        if (currentScrollY > 80) {
            nav.classList.add('scrolled');
            header.classList.add('scrolled');
        } else {
            nav.classList.remove('scrolled');
            header.classList.remove('scrolled');
        }

        // Always keep header visible - never hide it
        header.classList.remove('hidden');
    };

    // Run scroll effect on load and on scroll
    scrollEffect();
    window.addEventListener('scroll', scrollEffect, { passive: true });

    // =========================
    // BACKGROUND SLIDESHOW
    // =========================
    const slides = document.querySelectorAll('.background-slideshow .slide');
    let currentSlide = 0;
    const slideInterval = 5000; // Change slide every 5 seconds

    const showSlide = (index) => {
        slides.forEach(slide => slide.classList.remove('active'));
        if (slides[index]) {
            slides[index].classList.add('active');
        }
    };

    const nextSlide = () => {
        currentSlide = (currentSlide + 1) % slides.length;
        showSlide(currentSlide);
    };

    // Initialize slideshow
    if (slides.length > 0) {
        showSlide(0);
        setInterval(nextSlide, slideInterval);
    }

    // =========================
    // PRODUCT LIGHTBOX GALLERY
    // =========================
    const productCards = document.querySelectorAll('.product-card[data-product-index]');
    const lightbox = document.getElementById('product-lightbox');

    if (productCards.length && lightbox) {
        const lightboxImage = lightbox.querySelector('.product-lightbox__image');
        const lightboxTitle = lightbox.querySelector('#lightbox-title');
        const lightboxDescription = lightbox.querySelector('.product-lightbox__description');
        const lightboxPrice = lightbox.querySelector('.product-lightbox__price');
        const closeButtons = lightbox.querySelectorAll('[data-lightbox-close]');
        const nextButton = lightbox.querySelector('[data-lightbox-next]');
        const prevButton = lightbox.querySelector('[data-lightbox-prev]');

        const productsContent = Array.from(productCards).map(card => {
            const details = card.querySelector('.product-card__details');
            // support data-images (comma separated) per product; fallback to single data-image
            const imagesAttr = card.dataset.images || card.dataset.image || '';
            const images = imagesAttr.split(',').map(s => s.trim()).filter(Boolean);
            return {
                images,
                titleElement: details?.querySelector('h3'),
                descriptionElement: details?.querySelector('p'),
                priceElement: details?.querySelector('.price')
            };
        });

        let currentProductIndex = 0;
        let currentImageIndex = 0;

        const counterEl = lightbox.querySelector('.product-lightbox__counter');

        const updateLightboxContent = () => {
            const product = productsContent[currentProductIndex];
            const img = (product.images && product.images[currentImageIndex]) || product.images[0] || '';
            lightboxImage.src = img;
            const titleText = product.titleElement?.textContent?.trim() || '';
            lightboxImage.alt = titleText;
            lightboxTitle.textContent = titleText;
            lightboxDescription.textContent = product.descriptionElement?.textContent?.trim() || '';
            lightboxPrice.textContent = product.priceElement?.textContent?.trim() || '';

            // update counter (e.g., "1 / 3") and ensure it's visible
            if (counterEl) {
                const total = product.images?.length || 1;
                counterEl.textContent = `${currentImageIndex + 1} / ${total}`;
            }
        };

        const openLightbox = (index) => {
            currentProductIndex = index;
            currentImageIndex = 0;
            updateLightboxContent();
            lightbox.classList.add('open');
            lightbox.setAttribute('aria-hidden', 'false');
            document.body.style.overflow = 'hidden';
            // hide header while viewing the lightbox
            if (header) header.classList.add('hidden');
        };

        const closeLightbox = () => {
            lightbox.classList.remove('open');
            lightbox.setAttribute('aria-hidden', 'true');
            document.body.style.overflow = '';
            // restore header when closing lightbox
            if (header) header.classList.remove('hidden');
        };

        const showNext = () => {
            const imgs = productsContent[currentProductIndex].images;
            if (!imgs || imgs.length === 0) return;
            currentImageIndex = (currentImageIndex + 1) % imgs.length;
            updateLightboxContent();
        };

        const showPrev = () => {
            const imgs = productsContent[currentProductIndex].images;
            if (!imgs || imgs.length === 0) return;
            currentImageIndex = (currentImageIndex - 1 + imgs.length) % imgs.length;
            updateLightboxContent();
        };

        productCards.forEach((card, index) => {
            card.addEventListener('click', () => openLightbox(index));
            card.addEventListener('keydown', (event) => {
                if (event.key === 'Enter' || event.key === ' ') {
                    event.preventDefault();
                    openLightbox(index);
                }
            });
        });

        closeButtons.forEach(button => button.addEventListener('click', closeLightbox));
        nextButton?.addEventListener('click', showNext);
        prevButton?.addEventListener('click', showPrev);

        document.addEventListener('keydown', (event) => {
            if (!lightbox.classList.contains('open')) return;

            if (event.key === 'Escape') {
                closeLightbox();
            } else if (event.key === 'ArrowRight') {
                showNext();
            } else if (event.key === 'ArrowLeft') {
                showPrev();
            }
        });

        lightbox.addEventListener('click', (event) => {
            if (event.target.dataset.lightboxClose !== undefined) {
                closeLightbox();
            }
        });
    }
});